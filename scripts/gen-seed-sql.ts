// Generates supabase/seed.sql from the app's demo data (src/data/seed.ts), so the web demo and the database start identical.
// Dates are written relative to "today in Lagos" when the seed runs, so the demo always looks current.
// Usage: npm run db:seed
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { createSeed } from '../src/data/seed';
import type { Photo } from '../src/data/types';

const db = createSeed();

// ---------- helpers ----------

/** Stable uuid for a demo id like 'l_3', so re-generating gives the same ids. */
const uuid = (key: string | undefined | null): string | null => {
  if (!key) return null;
  const h = createHash('sha1').update(`solar-demo:${key}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const FIRM = uuid('firm')!;

const DAY_MS = 86_400_000;
const LAGOS_OFFSET_MS = 3_600_000; // Africa/Lagos is UTC+1 all year
const now = Date.now();
const lagosMidnight = Math.floor((now + LAGOS_OFFSET_MS) / DAY_MS) * DAY_MS - LAGOS_OFFSET_MS;
const ANCHOR = `(date_trunc('day', now() at time zone 'Africa/Lagos') at time zone 'Africa/Lagos')`;

type Lit = string;
const q = (v: unknown): Lit => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const num = (v: number | null | undefined): Lit => (v === null || v === undefined || Number.isNaN(v) ? 'null' : String(v));
const bool = (v: boolean | undefined): Lit => (v ? 'true' : 'false');
const json = (v: unknown): Lit => (v === undefined || v === null ? 'null' : `${q(JSON.stringify(v))}::jsonb`);
const id = (key: string | undefined | null): Lit => q(uuid(key));
const ts = (iso: string | undefined | null): Lit => {
  if (!iso) return 'null';
  const secs = Math.round((new Date(iso).getTime() - lagosMidnight) / 1000);
  return `${ANCHOR} + interval '${secs} seconds'`;
};
const phone = (p: string) => '+234' + p.replace(/\D/g, '').replace(/^0/, '').replace(/^234/, '');
const arr = (vals: Lit[], type: string): Lit => `array[${vals.join(', ')}]::${type}[]`;

const out: string[] = [
  '-- Generated by scripts/gen-seed-sql.ts from src/data/seed.ts. Do not edit by hand; run `npm run db:seed`.',
  '-- Demo firm: BrightPath Solar (Lagos). Sign in with any staff phone and code 123456 (see supabase/config.toml).',
  'begin;',
  '',
];

function insert(table: string, rows: Record<string, Lit>[], onConflict = '') {
  if (!rows.length) return;
  const cols = Object.keys(rows[0]);
  out.push(`insert into public.${table} (${cols.join(', ')}) values`);
  out.push(rows.map((r) => `  (${cols.map((c) => r[c]).join(', ')})`).join(',\n') + (onConflict ? `\n${onConflict}` : '') + ';', '');
}

// ---------- firm and people ----------

const c = db.company;
insert('firms', [
  {
    id: q(FIRM),
    name: q(c.name),
    address: q(c.address),
    state: q(c.state),
    phone: q(phone(c.phone)),
    bank_name: q(c.bankName),
    account_number: q(c.accountNumber),
    account_name: q(c.accountName),
    follow_up_days: num(c.followUpDays),
    service_interval_months: num(c.serviceIntervalMonths),
    labour_price: num(c.labourPrice),
    transport_price: num(c.transportPrice),
    default_valid_days: num(c.defaultValidDays),
    default_deposit_pct: num(c.defaultDepositPct),
    subscription_status: q(c.subscription.status),
    subscription_seats: num(c.subscription.seats),
    trial_ends_at: ts(c.subscription.trialEndsAt),
    paid_until: ts(c.subscription.paidUntil),
    setup_completed_at: ts(c.setupCompletedAt),
  },
]);

insert(
  'staff',
  db.users.map((u) => ({ id: id(u.id), firm_id: q(FIRM), name: q(u.name), phone: q(phone(u.phone)), role: q(u.role), title: q(u.title), active: bool(u.active) })),
);

// ---------- price list ----------

insert(
  'price_items',
  db.priceItems.map((p) => ({
    id: id(p.id),
    firm_id: q(FIRM),
    category: q(p.category),
    brand: q(p.brand),
    model: q(p.model),
    watts: num(p.watts),
    ah: num(p.ah),
    volts: num(p.volts),
    kwh: num(p.kwh),
    kva: num(p.kva),
    price: num(p.price),
    warranty_years: num(p.warrantyYears),
  })),
);
insert('price_item_costs', db.priceItems.map((p) => ({ item_id: id(p.id), firm_id: q(FIRM), cost: num(p.cost) })));
insert('plans', db.plans.map((p) => ({ id: id(p.id), firm_id: q(FIRM), name: q(p.name), price: num(p.price), visits_per_year: num(p.visitsPerYear) })));
insert('checklist_templates', db.checklistTemplates.map((t) => ({ firm_id: q(FIRM), job_type: q(t.jobType), steps: json(t.steps) })));

// ---------- leads, surveys, quotes ----------

insert(
  'leads',
  db.leads.map((l) => ({
    id: id(l.id),
    firm_id: q(FIRM),
    name: q(l.name),
    phone: q(phone(l.phone)),
    location: q(l.location),
    address: q(l.address),
    state: q(l.state),
    source: q(l.source),
    property_type: q(l.propertyType),
    stage: q(l.stage),
    notes: q(l.notes),
    whatsapp_consent: bool(l.whatsappConsent),
    created_at: ts(l.createdAt),
  })),
);

insert(
  'surveys',
  db.surveys.map((s) => ({
    id: id(s.id),
    firm_id: q(FIRM),
    lead_id: id(s.leadId),
    technician_id: id(s.technicianId),
    status: q(s.status),
    appliances: json(s.appliances),
    state: q(s.state),
    sun_hours: num(s.sunHours),
    backup_hours: num(s.backupHours),
    peak_w: num(s.peakW),
    daily_wh: num(s.dailyWh),
    recommended: json(s.recommended),
    override: json(s.override),
    created_at: ts(s.createdAt),
    submitted_at: s.status === 'submitted' ? ts(s.createdAt) : 'null',
  })),
);

insert(
  'quotes',
  db.quotes.map((x) => ({
    id: id(x.id),
    firm_id: q(FIRM),
    number: q(x.number),
    lead_id: id(x.leadId),
    survey_id: id(x.surveyId),
    status: q(x.status),
    valid_days: num(x.validDays),
    deposit_pct: num(x.depositPct),
    selected_option_id: id(x.selectedOptionId ? `${x.id}/${x.selectedOptionId}` : null),
    sent_at: ts(x.sentAt),
    accepted_at: ts(x.acceptedAt),
    last_follow_up_at: ts(x.lastFollowUpAt),
    created_at: ts(x.createdAt),
  })),
);
// Option and line ids are only unique within a quote in the demo data, so key them by quote
const options = db.quotes.flatMap((x) => x.options.map((o, i) => ({ x, o, i })));
insert(
  'quote_options',
  options.map(({ x, o, i }) => ({ id: id(`${x.id}/${o.id}`), firm_id: q(FIRM), quote_id: id(x.id), position: num(i), name: q(o.name), backup_hours: num(o.backupHours) })),
);
const lines = options.flatMap(({ x, o }) => o.lines.map((l, i) => ({ key: `${x.id}/${o.id}/${l.id}`, optKey: `${x.id}/${o.id}`, l, i })));
insert(
  'quote_lines',
  lines.map(({ key, optKey, l, i }) => ({
    id: id(key),
    firm_id: q(FIRM),
    option_id: id(optKey),
    position: num(i),
    item_id: id(l.itemId),
    category: q(l.category),
    description: q(l.description),
    qty: num(l.qty),
    unit_price: num(l.unitPrice),
  })),
);
// The trigger fills costs for lines with a price item; the demo's own costs (incl. labour and transport) win
insert(
  'quote_line_costs',
  lines.map(({ key, l }) => ({ line_id: id(key), firm_id: q(FIRM), unit_cost: num(l.unitCost) })),
  'on conflict (line_id) do update set unit_cost = excluded.unit_cost',
);

// ---------- jobs, installations, tickets ----------

insert(
  'jobs',
  db.jobs.map((j) => ({
    id: id(j.id),
    firm_id: q(FIRM),
    number: q(j.number),
    lead_id: id(j.leadId),
    type: q(j.type),
    status: q(j.status),
    quote_id: id(j.quoteId),
    start_at: ts(j.start),
    duration_hours: num(j.durationHours),
    address: q(j.address),
    lat: num(j.gps?.lat),
    lng: num(j.gps?.lng),
    equipment: json(j.equipment.map((e) => ({ ...e, itemId: uuid(e.itemId) }))),
    notes: q(j.notes),
    checklist: json(j.checklist),
    check_in_at: ts(j.checkIn?.at),
    check_out_at: ts(j.checkOut?.at),
    completed_at: ts(j.completedAt),
  })),
);
insert('job_assignees', db.jobs.flatMap((j) => j.assigneeIds.map((s) => ({ job_id: id(j.id), staff_id: id(s), firm_id: q(FIRM) }))));

insert(
  'installations',
  db.installations.map((i) => ({
    id: id(i.id),
    firm_id: q(FIRM),
    lead_id: id(i.leadId),
    job_id: id(i.jobId),
    installed_at: ts(i.installedAt),
    site: q(i.site),
    service_interval_months: num(i.serviceIntervalMonths),
    next_service_at: ts(i.nextServiceAt),
    last_service_reminder_at: ts(i.lastServiceReminderAt),
    plan_id: id(i.planId),
    plan_started_at: ts(i.planStartedAt),
    plan_renews_at: ts(i.planRenewsAt),
    plan_visits_left: num(i.planVisitsLeft),
  })),
);
insert('installation_technicians', db.installations.flatMap((i) => i.technicianIds.map((s) => ({ installation_id: id(i.id), staff_id: id(s), firm_id: q(FIRM) }))));
insert(
  'installation_items',
  db.installations.flatMap((i) =>
    i.items.map((it) => ({
      id: id(it.id),
      firm_id: q(FIRM),
      installation_id: id(i.id),
      label: q(it.label),
      category: q(it.category),
      serial: q(it.serial),
      warranty_years: num(it.warrantyYears),
      warranty_ends_at: ts(it.warrantyEndsAt),
    })),
  ),
);

insert(
  'tickets',
  db.tickets.map((t) => ({
    id: id(t.id),
    firm_id: q(FIRM),
    number: q(t.number),
    installation_id: id(t.installationId),
    lead_id: id(t.leadId),
    description: q(t.description),
    channel: q(t.channel),
    status: q(t.status),
    created_at: ts(t.createdAt),
  })),
);
insert('ticket_updates', db.tickets.flatMap((t) => t.updates.map((u, n) => ({ id: id(`${t.id}/u${n}`), firm_id: q(FIRM), ticket_id: id(t.id), at: ts(u.at), text: q(u.text) }))));

// Links between jobs, installations and tickets (circular, so set after both exist)
for (const j of db.jobs) {
  if (j.installationId || j.ticketId) out.push(`update public.jobs set installation_id = ${id(j.installationId)}, ticket_id = ${id(j.ticketId)} where id = ${id(j.id)};`);
}
for (const t of db.tickets) {
  const job = db.jobs.find((j) => j.ticketId === t.id);
  if (job) out.push(`update public.tickets set job_id = ${id(job.id)} where id = ${id(t.id)};`);
}
out.push('');

// ---------- money ----------

insert(
  'invoices',
  db.invoices.map((i) => ({
    id: id(i.id),
    firm_id: q(FIRM),
    number: q(i.number),
    lead_id: id(i.leadId),
    quote_id: id(i.quoteId),
    job_id: id(i.jobId),
    kind: q(i.kind),
    description: q(i.description),
    amount: num(i.amount),
    issued_at: ts(i.issuedAt),
    due_at: ts(i.dueAt),
    reminders_sent: arr(i.remindersSent.map(String), 'int'),
  })),
);
insert(
  'payments',
  db.payments.map((p) => ({
    id: id(p.id),
    firm_id: q(FIRM),
    invoice_id: id(p.invoiceId),
    amount: num(p.amount),
    method: q(p.method),
    at: ts(p.at),
    status: q(p.status),
    reference: q(p.reference),
    gateway_reference: ['Card', 'Transfer', 'USSD'].includes(p.method) ? q(`demo_${p.reference}`) : 'null',
    recorded_by: id(p.recordedById),
    approved_by: id(p.approvedById),
  })),
);

// ---------- photos (seeded photos have no image file) ----------

const photoRow = (p: Photo, parent: { survey_id?: string; job_id?: string; ticket_id?: string }) => ({
  id: id(p.id),
  firm_id: q(FIRM),
  kind: q(p.kind),
  storage_path: 'null',
  bytes: num(p.bytes),
  taken_at: ts(p.takenAt),
  lat: num(p.gps?.lat),
  lng: num(p.gps?.lng),
  survey_id: id(parent.survey_id),
  job_id: id(parent.job_id),
  ticket_id: id(parent.ticket_id),
});
insert('photos', [
  ...db.surveys.flatMap((s) => s.photos.map((p) => photoRow(p, { survey_id: s.id }))),
  ...db.jobs.flatMap((j) => j.photos.map((p) => photoRow(p, { job_id: j.id }))),
  ...db.tickets.flatMap((t) => t.photos.map((p) => photoRow(p, { ticket_id: t.id }))),
]);

insert(
  'notifications',
  db.notifications.map((n) => ({ id: id(n.id), firm_id: q(FIRM), text: q(n.text), link: q(n.link), for_roles: arr(n.forRoles.map(q), 'public.staff_role'), created_at: ts(n.at) })),
);

// ---------- counters, and an empty audit log (seeding isn't a user change) ----------

insert(
  'counters',
  Object.entries(db.counters).map(([prefix, value]) => ({ firm_id: q(FIRM), prefix: q(prefix), value: num(value) })),
);
out.push('delete from public.audit_log;', '', 'commit;', '');

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'));
console.log(`Wrote supabase/seed.sql (${db.leads.length} leads, ${db.jobs.length} jobs, ${db.invoices.length} invoices)`);
